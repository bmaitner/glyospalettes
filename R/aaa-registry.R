# Palette registry ---------------------------------------------------------
#
# Every palette in glyospalettes is defined here with its colors and metadata. The
# exported objects `glyos_palettes` and `glyos_colorways` are derived from this
# registry in R/palettes.R. Keep entries in one place so the two never drift.
#
# Hex values are hand-curated approximations. See data-raw/README.md for how
# they were sampled and reconciled against the manufacturers' descriptions.

cw <- function(palette, colours, colorway, company, line, year = NA_integer_,
               wave = NA_character_, description, reference, source) {
  list(
    palette = palette, colours = colours, colorway = colorway,
    company = company, line = line, year = as.integer(year),
    wave = as.character(wave), description = description,
    reference = reference, source = source
  )
}

db <- function(path) paste0("https://database.glyos.com/", path)
wiki <- function(title) {
  paste0("https://glyos.fandom.com/wiki/", utils::URLencode(gsub(" ", "_", title)))
}

